"""
evaluate_predictions.py
-----------------------
Loads eval_out/predictions.csv produced by evaluate_clip.py and prints
a comprehensive breakdown of coarse + fine classification performance.

USAGE:
    python evaluate_predictions.py

EXPECTED INPUT:
    eval_out/predictions.csv  (generated by evaluate_clip.py)
"""

import pandas as pd
import numpy as np
from pathlib import Path

PREDICTIONS_CSV = Path("eval_out/predictions.csv")


def accuracy(y_true, y_pred):
    y_true, y_pred = np.array(y_true), np.array(y_pred)
    return float((y_true == y_pred).mean()) if len(y_true) else float("nan")


def macro_f1(y_true, y_pred, labels):
    y_true, y_pred = np.array(y_true), np.array(y_pred)
    f1s = []
    for lab in labels:
        tp = np.sum((y_true == lab) & (y_pred == lab))
        fp = np.sum((y_true != lab) & (y_pred == lab))
        fn = np.sum((y_true == lab) & (y_pred != lab))
        if tp == 0 and (fp == 0 or fn == 0):
            f1 = 0.0
        else:
            prec = tp / (tp + fp) if (tp + fp) else 0.0
            rec  = tp / (tp + fn) if (tp + fn) else 0.0
            f1   = (2 * prec * rec / (prec + rec)) if (prec + rec) else 0.0
        f1s.append(f1)
    return float(np.mean(f1s)) if f1s else float("nan")


def print_section(title):
    print(f"\n{'='*60}")
    print(f"  {title}")
    print(f"{'='*60}")


def main():
    if not PREDICTIONS_CSV.exists():
        raise FileNotFoundError(f"Missing: {PREDICTIONS_CSV}. Run evaluate_clip.py first.")

    df = pd.read_csv(PREDICTIONS_CSV)
    df["true_fine"] = df["true_fine"].where(df["true_fine"].notna() & (df["true_fine"] != "nan"), other=np.nan)

    # ── COARSE OVERALL ────────────────────────────────────────────────────────
    print_section("COARSE METRICS — OVERALL")
    coarse_labels = sorted(df["true_coarse"].unique())
    coarse_acc = accuracy(df["true_coarse"], df["pred_coarse"])
    coarse_f1  = macro_f1(df["true_coarse"], df["pred_coarse"], labels=coarse_labels)
    print(f"  N          : {len(df)}")
    print(f"  Accuracy   : {coarse_acc:.4f}")
    print(f"  Macro-F1   : {coarse_f1:.4f}")

    # ── COARSE PER CLASS ──────────────────────────────────────────────────────
    print_section("COARSE ACCURACY BY CLASS")
    print(f"  {'Category':<15} {'N':<8} {'Accuracy':<10} {'F1'}")
    print(f"  {'-'*50}")
    for c in coarse_labels:
        sub = df[df["true_coarse"] == c]
        if len(sub) == 0:
            continue
        acc = accuracy(sub["true_coarse"], sub["pred_coarse"])
        f1  = macro_f1(sub["true_coarse"], sub["pred_coarse"], labels=[c])
        print(f"  {c:<15} {len(sub):<8} {acc:<10.4f} {f1:.4f}")

    # ── COARSE CONFUSION ─────────────────────────────────────────────────────
    print_section("COARSE CONFUSION — WHERE EACH CLASS IS MISCLASSIFIED")
    for c in coarse_labels:
        sub = df[df["true_coarse"] == c]
        wrong = sub[sub["pred_coarse"] != c]
        if len(wrong) == 0:
            print(f"\n  {c}: no misclassifications ✓")
            continue
        print(f"\n  {c} ({len(wrong)} misses):")
        for pred_cat, count in wrong["pred_coarse"].value_counts().items():
            print(f"    → predicted as '{pred_cat}': {count}")

    # ── FINE OVERALL ──────────────────────────────────────────────────────────
    print_section("FINE METRICS — OVERALL")
    fine_mode = df["fine_mode"].iloc[0] if "fine_mode" in df.columns else "unknown"
    print(f"  Fine mode  : {fine_mode}")

    fine_df = df[df["true_fine"].notna() & df["pred_fine"].notna()].copy()
    print(f"  N (evaluated): {len(fine_df)}")

    if len(fine_df) == 0:
        print("  No fine-evaluable rows found.")
        return

    fine_labels = sorted(fine_df["true_fine"].unique())
    fine_acc = accuracy(fine_df["true_fine"], fine_df["pred_fine"])
    fine_f1  = macro_f1(fine_df["true_fine"], fine_df["pred_fine"], labels=fine_labels)
    print(f"  Accuracy   : {fine_acc:.4f}")
    print(f"  Macro-F1   : {fine_f1:.4f}")

    # ── FINE PER CLASS ────────────────────────────────────────────────────────
    print_section("FINE ACCURACY BY CLASS (sorted worst → best)")
    fine_df["correct"] = fine_df["true_fine"] == fine_df["pred_fine"]
    per_class = (
        fine_df.groupby("true_fine")["correct"]
        .agg(["mean", "count"])
        .rename(columns={"mean": "accuracy", "count": "N"})
        .sort_values("accuracy")
    )
    print(f"  {'Fine label':<40} {'N':<8} {'Accuracy'}")
    print(f"  {'-'*60}")
    for label, row in per_class.iterrows():
        print(f"  {label:<40} {int(row['N']):<8} {row['accuracy']:.4f}")

    # ── FINE CONFUSION ────────────────────────────────────────────────────────
    print_section("FINE CONFUSION — WHERE EACH CLASS IS MISCLASSIFIED")
    for label in per_class.index:  # already sorted worst first
        sub = fine_df[fine_df["true_fine"] == label]
        wrong = sub[sub["pred_fine"] != label]
        if len(wrong) == 0:
            print(f"\n  {label}: no misclassifications ✓")
            continue
        print(f"\n  {label} ({len(wrong)} misses out of {len(sub)}):")
        for pred_label, count in wrong["pred_fine"].value_counts().items():
            print(f"    → predicted as '{pred_label}': {count}")

    # ── FINE BREAKDOWN BY COARSE ──────────────────────────────────────────────
    print_section("FINE ACCURACY GROUPED BY COARSE CATEGORY")
    for coarse in sorted(fine_df["fine_pool_coarse"].unique()):
        sub = fine_df[fine_df["fine_pool_coarse"] == coarse]
        if len(sub) == 0:
            continue
        acc = accuracy(sub["true_fine"], sub["pred_fine"])
        print(f"\n  [{coarse}]  N={len(sub)}  acc={acc:.4f}")
        sub_per_class = (
            sub.groupby("true_fine")["correct"]
            .agg(["mean", "count"])
            .rename(columns={"mean": "accuracy", "count": "N"})
            .sort_values("accuracy")
        )
        for label, row in sub_per_class.iterrows():
            print(f"    {label:<40} N={int(row['N']):<5} acc={row['accuracy']:.4f}")

    print(f"\n{'='*60}")
    print("  Done.")
    print(f"{'='*60}\n")


if __name__ == "__main__":
    main()